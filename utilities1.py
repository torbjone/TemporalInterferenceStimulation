def welch_autocorr(spike_times, bin_size, sim_time, segments=16, f=1000, demean=False, normalize=False):
    """This function finds the spike rate from the spike train to make a continuous array,
    and divides the array in overlapping segments, applies a hanning window function to avoid artifacts, 
    and takes the FFT of the autocorrelation of each segment and then takes the average 
    over all segments to find a Welch-likefourier transform of the autocorrelation"""

    spike_rate, _ = find_spike_rate(spike_times, bin_size, sim_time, demean=demean) # to make continuous signal

    x = np.asarray(spike_rate, dtype=float)
    N = len(x) # number of datapoints
    seg_len = N // segments # length of each segment

    step = seg_len // 2   # 50% overlap
    dt = bin_size / 1000.0 # seconds

    win = np.hanning(seg_len) # hanning window
    fft_segments = []

    for start in range(0, N - seg_len + 1, step): 
        seg = x[start:start + seg_len].copy() 

        # demean based on each segment 
        if demean:
            seg = seg - np.mean(seg) 

        # multiply the segment with the hanning window
        seg = seg * win 

        # autocorrelation
        r = np.correlate(seg, seg, mode="full") / seg_len

        r_shifted = np.fft.ifftshift(r) # rearrange the order of the signal

        fft_seg = np.real(np.fft.rfft(r_shifted)) * dt # fft
        fft_seg = np.maximum(fft_seg, 0) # remove negative values if any

        fft_segments.append(fft_seg)

    if len(fft_segments) == 0:
        return np.array([]), np.array([])

    min_len = min(len(p) for p in fft_segments) # finding shortest fft length
    fft_segments = np.array([p[:min_len] for p in fft_segments]) 
    fft = np.mean(fft_segments, axis=0)

    freqs = np.fft.rfftfreq(2 * seg_len - 1, d=dt)[:min_len]

    mask = freqs < f + 800

    if normalize:
        fft = fft / np.max(fft)
    return freqs[mask], fft[mask]

def psd_Vm(Vm, sim_time, resolution, segments=16, f=1000):
    """Computes the PSD-values of the membrane potential given:
    Vm : recorded membrane potential, 
    sim_time : duration of simulation
    bin_size : frequency resolution
    segments : number of segments the signal is to be divided into
    It returns PSD-values of the membrane potential, and corresponding frequencies"""
    
    fs = 1000.0 / resolution  # Sampling frequency [Hz]
    
    # using scipys Welch function to find frequencies and psd values. overlap fraction is 0.5 
    freqs, psd_values = welch(Vm, fs=fs, nperseg=len(Vm)//segments, noverlap=(len(Vm)//segments)//2)
    
    freqs = freqs[freqs<f+800]
    psd_values = psd_values[:len(freqs)]

    return freqs, psd_values

def autocorr_vm(Vm, normalize=False, demean=False):
    Vm = np.asarray(Vm, dtype=float)

    if demean:
        Vm = Vm - np.mean(Vm)

    r = np.correlate(Vm, Vm, mode="full")
    r = r[r.size // 2:]   # behold bare ikke-negative lag

    if normalize and r[0] != 0:
        r = r / r[0]

    return r

def psd_Vm_autocorr(Vm, sim_time, bin_size, resolution=0.25, f=1000):
    r = autocorr_vm(Vm, normalize=False, demean=True)

    dt = resolution / 1000.0
    psd = np.abs(np.fft.rfft(r)) * dt
    freqs = np.fft.rfftfreq(len(r), d=dt)

    keep = freqs < f + 800
    freqs = freqs[keep]
    psd = psd[keep]

    return freqs, psd






def simulated_SNR(Vm, a, psd_values,
                f, freqs, arg_f, sim_time,
                sd, beat, spike_times, 
                second_sine, 
                auto_freqs=None,
                auto_values=None):
    """This function calculates the SNR. It also creates and returns dataframe to display SNR and other data,
    providing functionality and control throughout simulations
    Vm : Recorded membrane potential
    a: amplitude of input current
    psd_values: PSD of spike-train
    f : frequency of input current 
    freqs : list of frequencies corresponding to PSD-values
    arg_f : argument in freqs closest to input frequency
    sim_time : duration of simulation
    sd : noise level (standard deviation of current)
    beat : modulation frequency
    spike_times : list of times when action pot. is recorded
    second_sine : whether or not the second AC-generator is connected"""
    
    window = 5  # 5 Hz-window around f

    # Finding the indexes of frequencies around the input frequency
    noise_mask = (freqs >= freqs[arg_f] - window) & (freqs <= freqs[arg_f] + window) & (freqs != freqs[arg_f])
    
    max_fft_value = np.max(np.abs(psd_values))
    fft_value_f = np.abs(psd_values[arg_f])
    max_freq = freqs[np.argmax(np.abs(psd_values))]

    # Local noise average 
    noise_avg = np.mean(psd_values[noise_mask])
    
    SNR = compute_SNR(freqs, psd_values, f)
    
    results_list = []


    # Creating dictionary to return results, separating between one and two AC-generators
    if second_sine:
        
        SNR_beat = compute_SNR(freqs, psd_values, beat)
        arg_beat = np.argmin(freqs-beat)
        noise_mask = (freqs >= freqs[arg_f] - window) & (freqs <= freqs[arg_f] + window) & (freqs != freqs[arg_f])
        noise_avg_beat = np.mean(psd_values[noise_mask])
        results_list.append({
        "Input Frequency (Hz)": [f, f+beat],
        "Beat Frequency (Hz)": beat,
        "Current Amplitude (pA)": a,
        "Max Vm (mV)": np.max(Vm),
        "SD Vm (mV)": np.std(Vm),
        "Max FFT Amplitude [(spikes per sec)/Hz]": np.round(max_fft_value,2),
        "PSD Amplitude for f [(spikes pr sec)/Hz]": round(fft_value_f,2),
        "PSD Amplitude for f2-f1 [(spikes pr sec)/Hz]": round(psd_values[arg_beat],2),
        "Frequency at max (Hz)": max_freq,
        "SNR (f)": round(SNR,2),
        "noise average": round(noise_avg,2),
        "Spike Rate (spikes/s)": (len(spike_times)/sim_time)*1000,
        "SNR (beat)": round(SNR_beat,1),
        "noise average (beat)" : round(noise_avg_beat,1),
        
        
    })
    else:
        results_list.append({
        "Input Frequency (Hz)": f,
        "Current Amplitude (pA)": a,
        "Max Vm (mV)": np.max(Vm),
        "SD Vm (mV)": np.std(Vm),
        "Max PSD Amplitude [(spikes per sec)/Hz]": round(max_fft_value,2),
        "PSD Amplitude for f [(spikes pr sec)/Hz]": round(fft_value_f,2),
        "Frequency at max (Hz)": max_freq,
        "SNR": round(SNR,2),
        "noise average": round(noise_avg,2),
        "Spike Rate (spikes/s)": (len(spike_times)/sim_time)*1000
            
    })

    if auto_values is not None:
        print("entered block")
        SNR_auto = compute_SNR(auto_freqs, auto_values, f)
        if second_sine:
            SNR_auto = compute_SNR(auto_freqs, auto_values, beat)
        #SNR_auto_vm = compute_SNR(auto_freqs_vm, auto_values_vm, f)
        results_list[0]["SNR (autocorr)"] = SNR_auto
        index = np.argmax(auto_values)
        results_list[0]["f at max (autocorr)"] = auto_freqs[index]
        
    # returning dictionary as dataframe to display data
    return pd.DataFrame(results_list), noise_avg


def compute_SNR(freqs, psd_values, f):
    """Computes and returns SNR given PSD_values and corresponding frequencies."""
    
    window = 5  # 5 Hz-window around f
    
    # Frequency closest to f 
    arg_f = np.argmin(np.abs(freqs-f))
    print("arg_f:", arg_f)
    # Finding the indexes of frequencies around the input frequency
    noise_mask = (freqs >= freqs[arg_f] - window) & (freqs <= freqs[arg_f] + window) & (freqs != freqs[arg_f])
    

    # Local noise average 
    noise_avg = np.mean(psd_values[noise_mask])
    
    # calculate SNR
    if noise_avg > 0:
        SNR = ((psd_values[arg_f]) / noise_avg)
    
    # Omit values that does not produce spikes
    else:
        SNR = np.nan
        
    return SNR