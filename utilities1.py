def find_spike_rate(spike_times, bin_size, sim_time, demean):
    #creating bins with width = bin_size (ms)
    t_bins = np.arange(0, sim_time + bin_size, bin_size)
    
    # putting spike train into the bins 
    spike_counts, _ = np.histogram(spike_times, bins=t_bins)
    
    # Spike rate
    spike_rate = spike_counts / (bin_size / 1000.0)

    if demean:
        spike_rate = spike_rate - spike_rate.mean()

    return spike_rate, spike_counts


def psd(spike_times, bin_size, sim_time, f, demean=False, normalize=False):
    spike_rate, _ = find_spike_rate(spike_times, bin_size, sim_time, demean=demean)
    
    dt = bin_size / 1000
    fs = 1 / dt
    
    fft_vals = np.fft.rfft(spike_rate)
    psd = (np.abs(fft_vals) ** 2) * dt  # viktig: squared

    
    freqs = np.fft.rfftfreq(len(spike_rate), d=dt)

    # # Cut off high-frequency tail to avoid artifacts near Nyquist
    mask = freqs < f + 800
    freqs = freqs[mask]
    psd = psd[mask]

    if normalize:
        psd = psd / np.max(psd)
    
    return freqs, psd

def psd_welch(spike_times, sim_time, bin_size=0.25, segments=16, f=1000, demean=False, normalize=False):
    """Computes the PSD of spiketrain given:
    spike_times : spike train, 
    sim_time : duration of simulation
    bin_size : frequency resolution
    segments : number of segments the signal is to be divided into
    It returns PSD-values of the spike train, and corresponding frequencies"""
    spike_rate, spike_counts = find_spike_rate(spike_times, bin_size, sim_time, demean)
    # Sampling rate (measurements per sec)
    fs = 1000 / bin_size 
    
    # using scipys Welch function to find frequencies and psd values. overlap fraction is 0.5 
    # This function splits the signal into overlapping segments, computes PSD for each segment and averages
    freqs, psd_values = welch(spike_rate, fs=fs, nperseg=len(spike_counts)//segments,
                              noverlap=(len(spike_counts)//segments)//2)
    
    if normalize:
        psd_values = psd_values / np.max(psd_values)
    

    # Cut off high-frequency tail to avoid artifacts near Nyquist
    mask = freqs < f + 800
    freqs = freqs[mask]
    psd = psd_values[mask]
    

    return freqs, psd


def autocorr(spike_times, bin_size, sim_time, normalize=False, demean=False):
    spike_rate, spike_counts = find_spike_rate(spike_times, bin_size, sim_time, demean)
    x = np.asarray(spike_rate, dtype=float)

    M = len(x)
    r = np.correlate(x, x, mode="full")   # length 2M - 1

    if normalize:
        lags = np.arange(-M + 1, M)       # same length as r
        r = r / (M - np.abs(lags))        # unbiased normalization 

    return r, spike_counts

